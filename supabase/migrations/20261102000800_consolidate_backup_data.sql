begin;

create table if not exists public.backup_data (
  id bigint generated by default as identity primary key,
  record_type text not null check (record_type in ('appointment', 'emergency_alert')),
  record_id text not null,
  snapshot jsonb not null,
  deleted_by uuid references auth.users(id) on delete set null,
  deleted_at timestamptz not null default now(),
  restored_at timestamptz
);
create index if not exists backup_data_type_deleted_at_idx
  on public.backup_data(record_type, deleted_at desc);

-- Move existing backups into the consolidated table before removing the old tables.
insert into public.backup_data(record_type, record_id, snapshot, deleted_by, deleted_at, restored_at)
select 'appointment', appointment_id::text, appointment_snapshot, deleted_by, deleted_at, restored_at
from public.appointment_deletion_backups
union all
select 'emergency_alert', alert_id::text, alert_snapshot, deleted_by, deleted_at, restored_at
from public.emergency_alert_deletion_backups;

alter table public.backup_data enable row level security;
revoke all on table public.backup_data from public, anon, authenticated;
grant select on table public.backup_data to authenticated;
grant update (restored_at) on table public.backup_data to authenticated;
drop policy if exists backup_data_admin_read on public.backup_data;
create policy backup_data_admin_read on public.backup_data
  for select to authenticated using (exists (
    select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin' and p.active is true
  ));
drop policy if exists backup_data_admin_restore_mark on public.backup_data;
create policy backup_data_admin_restore_mark on public.backup_data
  for update to authenticated using (exists (
    select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin' and p.active is true
  )) with check (exists (
    select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin' and p.active is true
  ));

create or replace function public.backup_deleted_appointment()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  insert into public.backup_data(record_type, record_id, snapshot, deleted_by)
  values ('appointment', old.id::text, to_jsonb(old), auth.uid());
  return old;
end;
$$;
revoke all on function public.backup_deleted_appointment() from public, anon, authenticated;
drop trigger if exists backup_appointment_before_delete on public.appointments;
create trigger backup_appointment_before_delete before delete on public.appointments
  for each row execute function public.backup_deleted_appointment();

create or replace function public.backup_deleted_emergency_alert()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  insert into public.backup_data(record_type, record_id, snapshot, deleted_by)
  values ('emergency_alert', old.id::text, to_jsonb(old), auth.uid());
  return old;
end;
$$;
revoke all on function public.backup_deleted_emergency_alert() from public, anon, authenticated;
drop trigger if exists backup_emergency_alert_before_delete on public.emergency_alerts;
create trigger backup_emergency_alert_before_delete before delete on public.emergency_alerts
  for each row execute function public.backup_deleted_emergency_alert();

create or replace function public.restore_deleted_appointment(p_backup_id bigint)
returns bigint language plpgsql security definer set search_path = public, pg_temp as $$
declare v_backup public.backup_data%rowtype;
begin
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active is true) then
    raise exception 'Active admin access is required.' using errcode = '42501';
  end if;
  select * into v_backup from public.backup_data
  where id = p_backup_id and record_type = 'appointment' and restored_at is null for update;
  if not found then raise exception 'Appointment backup not found or already restored.' using errcode = 'P0002'; end if;
  insert into public.appointments
  select (jsonb_populate_record(null::public.appointments, v_backup.snapshot)).*;
  update public.backup_data set restored_at = now() where id = p_backup_id;
  return v_backup.record_id::bigint;
end;
$$;
revoke all on function public.restore_deleted_appointment(bigint) from public, anon;
grant execute on function public.restore_deleted_appointment(bigint) to authenticated;

create or replace function public.restore_deleted_emergency_alert(p_backup_id bigint)
returns uuid language plpgsql security definer set search_path = public, pg_temp as $$
declare v_backup public.backup_data%rowtype;
begin
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active is true) then
    raise exception 'Active admin access is required.' using errcode = '42501';
  end if;
  select * into v_backup from public.backup_data
  where id = p_backup_id and record_type = 'emergency_alert' and restored_at is null for update;
  if not found then raise exception 'GPS alert backup not found or already restored.' using errcode = 'P0002'; end if;
  insert into public.emergency_alerts
  select (jsonb_populate_record(null::public.emergency_alerts, v_backup.snapshot)).*;
  update public.backup_data set restored_at = now() where id = p_backup_id;
  return v_backup.record_id::uuid;
end;
$$;
revoke all on function public.restore_deleted_emergency_alert(bigint) from public, anon;
grant execute on function public.restore_deleted_emergency_alert(bigint) to authenticated;

create or replace function public.permanently_delete_appointment_backup(p_backup_id bigint)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active is true) then
    raise exception 'Active admin access is required.' using errcode = '42501';
  end if;
  delete from public.backup_data where id = p_backup_id and record_type = 'appointment';
  if not found then raise exception 'Appointment backup not found.' using errcode = 'P0002'; end if;
end;
$$;
revoke all on function public.permanently_delete_appointment_backup(bigint) from public, anon;
grant execute on function public.permanently_delete_appointment_backup(bigint) to authenticated;

create or replace function public.permanently_delete_emergency_alert_backup(p_backup_id bigint)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active is true) then
    raise exception 'Active admin access is required.' using errcode = '42501';
  end if;
  delete from public.backup_data where id = p_backup_id and record_type = 'emergency_alert';
  if not found then raise exception 'GPS alert backup not found.' using errcode = 'P0002'; end if;
end;
$$;
revoke all on function public.permanently_delete_emergency_alert_backup(bigint) from public, anon;
grant execute on function public.permanently_delete_emergency_alert_backup(bigint) to authenticated;

-- Both backup types now live in backup_data; these former tables are empty of responsibility.
drop table public.appointment_deletion_backups;
drop table public.emergency_alert_deletion_backups;

commit;

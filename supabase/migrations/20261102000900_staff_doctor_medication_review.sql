begin;

-- Medication requests are kept pending until a Doctor reviews them. Approved
-- medication details are appended to the existing patients.prescriptions JSON.
create table if not exists public.medication_review_orders (
  id bigint generated by default as identity primary key,
  patient_id text not null references public.patients(id) on delete restrict,
  nurse_user_id uuid not null references auth.users(id) on delete restrict,
  doctor_staff_id text not null references public.staff(id) on delete restrict,
  medications jsonb not null default '[]'::jsonb check (jsonb_typeof(medications) = 'array'),
  nurse_note text not null default '',
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  doctor_note text not null default '',
  reviewed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create index if not exists medication_review_orders_doctor_pending_idx
  on public.medication_review_orders(doctor_staff_id, status, created_at desc);
create index if not exists medication_review_orders_patient_created_idx
  on public.medication_review_orders(patient_id, created_at desc);

alter table public.medication_review_orders enable row level security;
grant select on public.medication_review_orders to authenticated;
drop policy if exists medication_review_orders_nurse_or_doctor_read on public.medication_review_orders;
create policy medication_review_orders_nurse_or_doctor_read
  on public.medication_review_orders for select to authenticated using (
    (nurse_user_id = (select auth.uid()) and public.erecpass_is_active_nurse(auth.uid()))
    or exists (
      select 1 from public.staff s
      where s.id = medication_review_orders.doctor_staff_id
        and s.user_id = (select auth.uid())
        and public.erecpass_is_active_doctor(auth.uid())
    )
  );

create or replace function public.nurse_list_medication_patients()
returns table(patient_id text, full_name text, current_prescriptions jsonb, assigned_doctor_staff_id text)
language plpgsql stable security definer set search_path = pg_catalog, public as $$
begin
  if not public.erecpass_is_active_nurse(auth.uid()) then
    raise exception 'Active Nurse access is required.' using errcode = '42501';
  end if;
  return query
  select p.id, p.full_name, coalesce(p.prescriptions, '[]'::jsonb), latest.provider_staff_id
  from public.patients p
  left join lateral (
    select a.provider_staff_id
    from public.appointments a
    where a.patient_id = p.id
      and a.provider_staff_id is not null
      and lower(btrim(a.status)) in ('assigned', 'pending', 'pending approval', 'approved')
    order by a.appointment_date desc, a.updated_at desc nulls last, a.id desc
    limit 1
  ) latest on true
  where p.active is distinct from false
  order by p.full_name;
end $$;
revoke all on function public.nurse_list_medication_patients() from public, anon;
grant execute on function public.nurse_list_medication_patients() to authenticated;

create or replace function public.nurse_list_medication_doctors()
returns table(staff_id text, full_name text, specialty text)
language plpgsql stable security definer set search_path = pg_catalog, public as $$
begin
  if not public.erecpass_is_active_nurse(auth.uid()) then
    raise exception 'Active Nurse access is required.' using errcode = '42501';
  end if;
  return query
  select s.id, s.name, coalesce(nullif(btrim(d.specialty), ''), 'Not specified')
  from public.staff s
  join public.profiles p on p.id = s.user_id and p.role = 'staff' and p.active = true
  join public.doctor_profiles d on d.staff_id = s.id and d.consultation_available = true
  where s.active = true and s.account_type = 'doctor'
  order by s.name;
end $$;
revoke all on function public.nurse_list_medication_doctors() from public, anon;
grant execute on function public.nurse_list_medication_doctors() to authenticated;

create or replace function public.nurse_submit_medication_order(
  p_patient_id text,
  p_doctor_staff_id text,
  p_medications jsonb,
  p_nurse_note text default ''
) returns bigint
language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_order_id bigint;
begin
  if not public.erecpass_is_active_nurse(auth.uid()) then
    raise exception 'Active Nurse access is required.' using errcode = '42501';
  end if;
  if not exists (select 1 from public.patients p where p.id = p_patient_id and p.active is distinct from false) then
    raise exception 'Active patient record not found.' using errcode = 'P0002';
  end if;
  if not exists (
    select 1 from public.staff s
    join public.profiles p on p.id = s.user_id and p.role = 'staff' and p.active = true
    join public.doctor_profiles d on d.staff_id = s.id and d.consultation_available = true
    where s.id = p_doctor_staff_id and s.active = true and s.account_type = 'doctor'
  ) then
    raise exception 'Choose an active Doctor who can receive medication requests.' using errcode = '22023';
  end if;
  if jsonb_typeof(p_medications) is distinct from 'array' then
    raise exception 'Medication requests must be submitted as a list.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_medications) < 1 or jsonb_array_length(p_medications) > 10 then
    raise exception 'Provide between 1 and 10 proposed medications.' using errcode = '22023';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_medications) item
    where jsonb_typeof(item) <> 'object'
       or nullif(btrim(item->>'medicine'), '') is null
       or nullif(btrim(item->>'dosage'), '') is null
       or length(item->>'medicine') > 160
       or length(item->>'dosage') > 120
       or length(coalesce(item->>'frequency', '')) > 120
       or length(coalesce(item->>'duration', '')) > 120
       or length(coalesce(item->>'instructions', '')) > 500
  ) then
    raise exception 'Each proposed medication needs a name and dosage, with fields within the allowed length.' using errcode = '22023';
  end if;
  insert into public.medication_review_orders(patient_id, nurse_user_id, doctor_staff_id, medications, nurse_note)
  values (p_patient_id, auth.uid(), p_doctor_staff_id, p_medications, left(coalesce(p_nurse_note, ''), 500))
  returning id into v_order_id;
  return v_order_id;
end $$;
revoke all on function public.nurse_submit_medication_order(text, text, jsonb, text) from public, anon;
grant execute on function public.nurse_submit_medication_order(text, text, jsonb, text) to authenticated;

create or replace function public.doctor_list_medication_review_orders()
returns table(
  id bigint, patient_id text, patient_name text, nurse_name text,
  medications jsonb, nurse_note text, current_prescriptions jsonb, created_at timestamptz
)
language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare
  v_doctor_staff_id text;
  v_is_admin boolean;
begin
  select exists(select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active = true)
  into v_is_admin;
  if not v_is_admin and not public.erecpass_is_active_doctor(auth.uid()) then
    raise exception 'Active Doctor access is required.' using errcode = '42501';
  end if;
  select s.id into v_doctor_staff_id from public.staff s
  where s.user_id = auth.uid() and s.active = true and s.account_type = 'doctor';
  if v_doctor_staff_id is null and not v_is_admin then
    raise exception 'Active Doctor profile not found.' using errcode = '42501';
  end if;
  return query
  select o.id, o.patient_id, p.full_name,
    coalesce(n.full_name, 'Nurse'), o.medications, o.nurse_note,
    coalesce(p.prescriptions, '[]'::jsonb), o.created_at
  from public.medication_review_orders o
  join public.patients p on p.id = o.patient_id
  left join public.profiles n on n.id = o.nurse_user_id
  where (v_is_admin or o.doctor_staff_id = v_doctor_staff_id) and o.status = 'pending'
  order by o.created_at;
end $$;
revoke all on function public.doctor_list_medication_review_orders() from public, anon;
grant execute on function public.doctor_list_medication_review_orders() to authenticated;

create or replace function public.doctor_review_medication_order(
  p_order_id bigint,
  p_decision text,
  p_medications jsonb default '[]'::jsonb,
  p_doctor_note text default ''
) returns void
language plpgsql security definer set search_path = pg_catalog, public as $$
declare
  v_doctor_staff_id text;
  v_order public.medication_review_orders%rowtype;
  v_current jsonb;
  v_final jsonb;
  v_is_admin boolean;
begin
  select exists(select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active = true)
  into v_is_admin;
  if not v_is_admin and not public.erecpass_is_active_doctor(auth.uid()) then
    raise exception 'Active Doctor access is required.' using errcode = '42501';
  end if;
  if p_decision not in ('approve', 'reject') then
    raise exception 'Choose approve or reject.' using errcode = '22023';
  end if;
  select s.id into v_doctor_staff_id from public.staff s
  where s.user_id = auth.uid() and s.active = true and s.account_type = 'doctor';
  select * into v_order from public.medication_review_orders
  where id = p_order_id for update;
  if not found or (not v_is_admin and v_order.doctor_staff_id <> v_doctor_staff_id) or v_order.status <> 'pending' then
    raise exception 'Medication request not found, already reviewed, or assigned to another Doctor.' using errcode = 'P0002';
  end if;

  if p_decision = 'approve' then
    if jsonb_typeof(p_medications) is distinct from 'array' then
      raise exception 'Final medications must be submitted as a list.' using errcode = '22023';
    end if;
    if jsonb_array_length(p_medications) < 1 or jsonb_array_length(p_medications) > 10 then
      raise exception 'Provide between 1 and 10 final medications.' using errcode = '22023';
    end if;
    if exists (
      select 1 from jsonb_array_elements(p_medications) item
      where jsonb_typeof(item) <> 'object'
         or nullif(btrim(item->>'medicine'), '') is null
         or nullif(btrim(item->>'dosage'), '') is null
         or length(item->>'medicine') > 160
         or length(item->>'dosage') > 120
         or length(coalesce(item->>'frequency', '')) > 120
         or length(coalesce(item->>'duration', '')) > 120
         or length(coalesce(item->>'instructions', '')) > 500
    ) then
      raise exception 'Each approved medication needs a name and confirmed dosage, with fields within the allowed length.' using errcode = '22023';
    end if;
    select coalesce(p.prescriptions, '[]'::jsonb) into v_current
    from public.patients p where p.id = v_order.patient_id for update;
    if jsonb_typeof(v_current) <> 'array' then v_current := jsonb_build_array(v_current); end if;
    select jsonb_agg(
      jsonb_build_object(
        'medicine', btrim(item->>'medicine'), 'dosage', btrim(item->>'dosage'),
        'frequency', btrim(coalesce(item->>'frequency', '')),
        'duration', btrim(coalesce(item->>'duration', '')),
        'days', btrim(coalesce(item->>'duration', '')),
        'instructions', btrim(coalesce(item->>'instructions', '')),
        'active', true, 'prescribed_at', now(), 'prescribed_by', auth.uid(),
        'medication_order_id', p_order_id
      )
    ) into v_final from jsonb_array_elements(p_medications) item;
    update public.patients set prescriptions = v_current || coalesce(v_final, '[]'::jsonb)
    where id = v_order.patient_id;
  else
    v_final := v_order.medications;
  end if;

  update public.medication_review_orders
  set status = case when p_decision = 'approve' then 'approved' else 'rejected' end,
      medications = coalesce(v_final, '[]'::jsonb), doctor_note = left(coalesce(p_doctor_note, ''), 500),
      reviewed_by = auth.uid(), reviewed_at = now()
  where id = p_order_id;
end $$;
revoke all on function public.doctor_review_medication_order(bigint, text, jsonb, text) from public, anon;
grant execute on function public.doctor_review_medication_order(bigint, text, jsonb, text) to authenticated;

commit;

begin;

create table if not exists public.emergency_alert_deletion_backups (
  id bigint generated by default as identity primary key,
  alert_id uuid not null,
  alert_snapshot jsonb not null,
  deleted_by uuid references auth.users(id) on delete set null,
  deleted_at timestamptz not null default now(),
  restored_at timestamptz
);
create index if not exists emergency_alert_deletion_backups_deleted_at_idx
  on public.emergency_alert_deletion_backups (deleted_at desc);

create or replace function public.backup_deleted_emergency_alert()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  insert into public.emergency_alert_deletion_backups(alert_id, alert_snapshot, deleted_by)
  values (old.id, to_jsonb(old), auth.uid());
  return old;
end;
$$;
revoke all on function public.backup_deleted_emergency_alert() from public, anon, authenticated;
drop trigger if exists backup_emergency_alert_before_delete on public.emergency_alerts;
create trigger backup_emergency_alert_before_delete before delete on public.emergency_alerts
  for each row execute function public.backup_deleted_emergency_alert();

alter table public.emergency_alert_deletion_backups enable row level security;
revoke all on table public.emergency_alert_deletion_backups from public, anon, authenticated;
grant select on table public.emergency_alert_deletion_backups to authenticated;
drop policy if exists emergency_alert_backups_admin_read on public.emergency_alert_deletion_backups;
create policy emergency_alert_backups_admin_read on public.emergency_alert_deletion_backups
  for select to authenticated using (exists (
    select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin' and p.active is true
  ));

grant update (restored_at) on public.emergency_alert_deletion_backups to authenticated;
drop policy if exists emergency_alert_backups_admin_update on public.emergency_alert_deletion_backups;
create policy emergency_alert_backups_admin_update on public.emergency_alert_deletion_backups
  for update to authenticated using (exists (
    select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin' and p.active is true
  )) with check (exists (
    select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin' and p.active is true
  ));

create or replace function public.admin_delete_emergency_alert(p_alert_id uuid)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active is true) then
    raise exception 'Active admin access is required.' using errcode = '42501';
  end if;
  delete from public.emergency_alerts where id = p_alert_id;
  if not found then raise exception 'Emergency alert not found.' using errcode = 'P0002'; end if;
end;
$$;
revoke all on function public.admin_delete_emergency_alert(uuid) from public, anon;
grant execute on function public.admin_delete_emergency_alert(uuid) to authenticated;

create or replace function public.restore_deleted_emergency_alert(p_backup_id bigint)
returns uuid language plpgsql security definer set search_path = public, pg_temp as $$
declare v_backup public.emergency_alert_deletion_backups%rowtype;
begin
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and p.active is true) then
    raise exception 'Active admin access is required.' using errcode = '42501';
  end if;
  select * into v_backup from public.emergency_alert_deletion_backups where id = p_backup_id and restored_at is null for update;
  if not found then raise exception 'Backup not found or already restored.' using errcode = 'P0002'; end if;
  insert into public.emergency_alerts select (jsonb_populate_record(null::public.emergency_alerts, v_backup.alert_snapshot)).*;
  update public.emergency_alert_deletion_backups set restored_at = now() where id = p_backup_id;
  return v_backup.alert_id;
end;
$$;
revoke all on function public.restore_deleted_emergency_alert(bigint) from public, anon;
grant execute on function public.restore_deleted_emergency_alert(bigint) to authenticated;

commit;

begin;

create table if not exists public.appointment_deletion_backups (
  id bigint generated by default as identity primary key,
  appointment_id bigint not null,
  appointment_snapshot jsonb not null,
  deleted_by uuid references auth.users(id) on delete set null,
  deleted_at timestamptz not null default now(),
  restored_at timestamptz
);
create index if not exists appointment_deletion_backups_deleted_at_idx
  on public.appointment_deletion_backups (deleted_at desc);

create or replace function public.backup_deleted_appointment()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.appointment_deletion_backups(appointment_id, appointment_snapshot, deleted_by)
  values (old.id, to_jsonb(old), auth.uid());
  return old;
end;
$$;
revoke all on function public.backup_deleted_appointment() from public, anon, authenticated;
drop trigger if exists backup_appointment_before_delete on public.appointments;
create trigger backup_appointment_before_delete
  before delete on public.appointments
  for each row execute function public.backup_deleted_appointment();

alter table public.appointment_deletion_backups enable row level security;
revoke all on table public.appointment_deletion_backups from public, anon, authenticated;
grant select on table public.appointment_deletion_backups to authenticated;
drop policy if exists appointment_deletion_backups_admin_read on public.appointment_deletion_backups;
create policy appointment_deletion_backups_admin_read
  on public.appointment_deletion_backups for select to authenticated
  using (exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin' and p.active is true
  ));

grant update (restored_at) on public.appointment_deletion_backups to authenticated;
drop policy if exists appointment_deletion_backups_admin_restore_mark on public.appointment_deletion_backups;
create policy appointment_deletion_backups_admin_restore_mark
  on public.appointment_deletion_backups for update to authenticated
  using (exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin' and p.active is true
  ))
  with check (exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin' and p.active is true
  ));

create or replace function public.restore_deleted_appointment(p_backup_id bigint)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_backup public.appointment_deletion_backups%rowtype;
begin
  if not exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin' and p.active is true
  ) then
    raise exception 'Active admin access is required.' using errcode = '42501';
  end if;
  select * into v_backup from public.appointment_deletion_backups
    where id = p_backup_id and restored_at is null for update;
  if not found then raise exception 'Backup not found or already restored.' using errcode = 'P0002'; end if;
  insert into public.appointments
  select (jsonb_populate_record(null::public.appointments, v_backup.appointment_snapshot)).*;
  update public.appointment_deletion_backups set restored_at = now() where id = p_backup_id;
  return v_backup.appointment_id;
end;
$$;
revoke all on function public.restore_deleted_appointment(bigint) from public, anon;
grant execute on function public.restore_deleted_appointment(bigint) to authenticated;

commit;
